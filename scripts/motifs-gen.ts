/**
 * docs/agents/ux-ui/motifs.json (UX/UI masters, Heritage-reviewed) -> registry/qatt/lib/qatt-motifs.ts
 * Run: pnpm motifs:gen. The output is committed; never hand-edit it.
 */
import fs from "node:fs"
import path from "node:path"

import { ROOT } from "./registry-lib"

type Variant = { id: string; width: number; height: number; slots: number; markup: string }
type Motif = {
  id: string
  arabicName: string
  englishName: string
  traditionalName: boolean
  width: number
  height: number
  repeat: "x" | "xy" | "none"
  slots: number
  defaultSlots: string[]
  mirror: boolean
  flipInRtl: boolean
  projectExtension: boolean
  aboutVocabulary: boolean
  uses: string[]
  markup: string
  variants: Variant[]
}

const src = JSON.parse(fs.readFileSync(path.join(ROOT, "docs/agents/ux-ui/motifs.json"), "utf8")) as {
  version?: string
  slotFallbacks: Record<string, string>
  motifs: Motif[]
}

const ids = src.motifs.map((m) => m.id)
const variantIds = [...new Set(src.motifs.flatMap((m) => m.variants.map((v) => v.id)))]
const lit = (v: unknown) => JSON.stringify(v)

const motifs = src.motifs
  .map((m) => {
    if (m.flipInRtl) throw new Error(`${m.id}: flipInRtl must be false (D-007)`)
    const variants = m.variants
      .map(
        (v) =>
          `      { id: ${lit(v.id)}, width: ${v.width}, height: ${v.height}, slots: ${v.slots}, markup: ${lit(v.markup)} },`,
      )
      .join("\n")
    return `  ${lit(m.id)}: {
    id: ${lit(m.id)},
    arabicName: ${lit(m.arabicName)},
    englishName: ${lit(m.englishName)},
    traditionalName: ${m.traditionalName},
    width: ${m.width},
    height: ${m.height},
    repeat: ${lit(m.repeat)},
    slots: ${m.slots},
    defaultSlots: ${lit(m.defaultSlots)},
    mirror: ${m.mirror},
    flipInRtl: false,
    projectExtension: ${m.projectExtension},
    aboutVocabulary: ${m.aboutVocabulary},
    uses: ${lit(m.uses)},
    markup: ${lit(m.markup)},
    variants: [${variants ? `\n${variants}\n    ` : ""}],
  },`
  })
  .join("\n")

const out = `// GENERATED by scripts/motifs-gen.ts from docs/agents/ux-ui/motifs.json — do not edit by hand.
//
// Qatt motif registry. Geometry is project interpretation (motif-catalog.md); names follow the Heritage catalog.
// Every tile paints with var(--qatt-slot-1..4, <fallback>): slot-1/2/3 = catalog colours A/B/C, slot-4 = ground.
// mirror = mirror-safe under horizontal reflection. flipInRtl is false for every motif: artwork never mirrors
// in RTL (sawtooth is the one directional motif and still renders identically, D-007).
// projectExtension = not documented in Al-Qatt sources (stepped, D-020): always label it in docs.

import type * as React from "react"

export type QattPigment = "white" | "jiss" | "red" | "yellow" | "black" | "blue" | "green" | "orange" | "brown" | "ink"
/** A pigment name or any CSS colour / var(). */
export type QattColor = QattPigment | (string & {})
export type MotifId = ${ids.map(lit).join(" | ")}
export type MotifVariant = ${variantIds.map(lit).join(" | ")}
export type MotifUse = "band" | "border" | "background" | "corner" | "cap"

export interface MotifTile {
  width: number
  height: number
  slots: number
  markup: string
}

export interface MotifDef extends MotifTile {
  id: MotifId
  arabicName: string
  englishName: string
  traditionalName: boolean
  repeat: "x" | "xy" | "none"
  defaultSlots: QattPigment[]
  mirror: boolean
  flipInRtl: false
  projectExtension: boolean
  aboutVocabulary: boolean
  uses: MotifUse[]
  variants: (MotifTile & { id: MotifVariant })[]
}

export const SLOT_FALLBACKS = ${lit(src.slotFallbacks)} as const

export const MOTIFS: Record<MotifId, MotifDef> = {
${motifs}
}

export const MOTIF_IDS = Object.keys(MOTIFS) as MotifId[]

const PIGMENTS: readonly string[] = ["white", "jiss", "red", "yellow", "black", "blue", "green", "orange", "brown", "ink"]

/** Pigment name -> var(--qatt-<name>); anything else (hex, oklch(), var()) passes through. */
export function resolveColor(c: QattColor): string {
  return PIGMENTS.includes(c) ? \`var(--qatt-\${c})\` : c
}

/** The tile for a motif (or one of its variants). Unknown variants fall back to the base tile. */
export function getMotifTile(id: MotifId, variant?: MotifVariant): MotifTile {
  const def = MOTIFS[id]
  return (variant && def.variants.find((v) => v.id === variant)) || def
}

/** Inline style setting --qatt-slot-1..4 from colours (falls back to the motif's default slots). */
export function slotStyle(id: MotifId, colors?: QattColor[], ground?: QattColor): React.CSSProperties {
  const slots = colors && colors.length ? colors : MOTIFS[id].defaultSlots
  const style: Record<string, string> = {}
  slots.slice(0, 3).forEach((c, i) => {
    style[\`--qatt-slot-\${i + 1}\`] = resolveColor(c)
  })
  if (ground) style["--qatt-slot-4"] = resolveColor(ground)
  return style as React.CSSProperties
}

/**
 * Standalone SVG data URI for CSS backgrounds/masks. CSS variables do not work inside data URIs,
 * so pass RESOLVED colours (slot 1..3, then ground). Missing slots use the catalog fallbacks.
 * \`rotate\` turns the tile by 90° steps (for vertical strips).
 */
export function motifToDataUri(
  id: MotifId,
  resolvedColors: string[] = [],
  variant?: MotifVariant,
  { ground, rotate = 0 }: { ground?: string; rotate?: 0 | 90 | 180 | 270 } = {},
): string {
  const tile = getMotifTile(id, variant)
  let markup = tile.markup.replace(/var\\(--qatt-slot-(\\d), ([^)]+)\\)/g, (_m, n: string, fallback: string) => {
    const i = Number(n)
    if (i === 4) return ground ?? fallback
    return resolvedColors[i - 1] ?? fallback
  })
  const quarter = rotate === 90 || rotate === 270
  const w = quarter ? tile.height : tile.width
  const h = quarter ? tile.width : tile.height
  if (rotate) markup = \`<g transform="translate(\${w / 2} \${h / 2}) rotate(\${rotate}) translate(\${-tile.width / 2} \${-tile.height / 2})">\${markup}</g>\`
  const svg = \`<svg xmlns="http://www.w3.org/2000/svg" width="\${w}" height="\${h}" viewBox="0 0 \${w} \${h}">\${markup}</svg>\`
  return \`url("data:image/svg+xml,\${encodeURIComponent(svg)}")\`
}

/** Back-compat alias (Phase 3). */
export function getMotif(id: MotifId): MotifDef {
  return MOTIFS[id]
}
`
const target = path.join(ROOT, "registry/qatt/lib/qatt-motifs.ts")
fs.writeFileSync(target, out)
console.log(`motifs-gen: ${ids.length} motifs, ${variantIds.length} variant ids -> ${path.relative(ROOT, target)}`)
