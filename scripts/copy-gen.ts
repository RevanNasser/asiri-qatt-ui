/**
 * docs/agents/heritage/site-copy.ar.md (Heritage-owned) -> lib/copy.ar.generated.ts
 * Run: pnpm copy:gen. The output is committed; never hand-edit it, and never write Arabic in code:
 * ask the Heritage agent to add a key to site-copy.ar.md, then re-run this script.
 */
import fs from "node:fs"
import path from "node:path"

import { ROOT } from "./registry-lib"

const SRC = path.join(ROOT, "docs/agents/heritage/site-copy.ar.md")
const OUT = path.join(ROOT, "lib/copy.ar.generated.ts")

// | `key` | text |   (a key may carry an italic note: | `key` *(…)* | text |)
const ROW = /^\|\s*`([A-Za-z0-9.\-_]+)`(?:\s*\*\([^)]*\)\*)?\s*\|\s*(.*?)\s*\|\s*$/

const entries: [string, string][] = []
const seen = new Set<string>()
for (const line of fs.readFileSync(SRC, "utf8").split("\n")) {
  const m = ROW.exec(line)
  if (!m) continue
  const [, key, text] = m as unknown as [string, string, string]
  if (seen.has(key)) throw new Error(`copy-gen: duplicate key ${key}`)
  seen.add(key)
  entries.push([key, text])
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/copy-gen.ts from docs/agents/heritage/site-copy.ar.md. Do not edit.\n` +
    `export const arCopy = {\n${body}\n} as const\n`,
)
console.log(`copy-gen: ${entries.length} keys -> ${path.relative(ROOT, OUT)}`)
